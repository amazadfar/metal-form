/**
 * Final concept-first localisation rewrite.
 *
 * These replacements intentionally do not mirror English syntax. Each locale
 * expresses the same engineering and commercial point in its own professional
 * register. Paths are patched through the guarded JSON patcher so a missing or
 * renamed content key fails instead of silently creating unused copy.
 */
import { apply } from './patch.mjs';

const locales = ['en', 'ru', 'hy', 'tr', 'th', 'zh', 'ur', 'ar', 'fa'];
const changes = new Map();

function queue(locale, file, path, value) {
  const target = `src/content/${locale}/${file}.json`;
  if (!changes.has(target)) changes.set(target, []);
  changes.get(target).push([path, value]);
}

function all(file, path, values) {
  for (const locale of locales) queue(locale, file, path, values[locale]);
}

